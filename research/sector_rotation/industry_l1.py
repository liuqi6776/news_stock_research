def build_l1_map(ind_map):
    """ind_map: {ts_code: 通达信110细分行业} → {ts_code: 申万一级}。

    未匹配的细分行业归入 '其他'（理论上 110 全覆盖）。
    """
    return {code: TDX_TO_SW_L1.get(ind, "其他") for code, ind in ind_map.items()}


def missing_industries(ind_map):
    """返回 ind_map 中未被 TDX_TO_SW_L1 覆盖的细分行业集合（用于自检）。"""
    return sorted(set(v for v in ind_map.values() if v not in TDX_TO_SW_L1))


